#include <stdio.h>

int main()
{
    float celsius,fahrenheit;

    printf("请输入摄氏温度:");

    scanf("%f",&celsius);

    fahrenheit = celsius * 9.0 / 5.0 + 32.0;

    printf("转换后的华氏温度为：%.1f\n", fahrenheit);

    return 0;
}//
